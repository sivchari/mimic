const suite = "../../testdata/suite"

func generate(t *testing.T, outPath string, specs ...string) (string, error) {
	t.Helper()

	return generateWith(t, emit.Options{OutPath: outPath}, specs...)
}

func generateWith(t *testing.T, opts emit.Options, specs ...string) (string, error) {
	t.Helper()

	l, err := load.New(suite)
	if err != nil {
		t.Fatal(err)
	}

	var its []*iface.Interface

	for _, s := range specs {
		i := strings.LastIndex(s, ".")

		it, err := iface.Load(l, s[:i], s[i+1:])
		if err != nil {
			t.Fatal(err)
		}

		its = append(its, it)
	}

	opts.Package = "mocks"

	src, err := emit.Generate(l, opts, its)

	return string(src), err
}

func TestGenerate_Shape(t *testing.T) {
	t.Parallel()

	src, err := generate(t, "example.com/suite/out", "example.com/suite/domain.Repo", "example.com/suite/domain.Var")
	if err != nil {
		t.Fatal(err)
	}

	if _, err := parser.ParseFile(token.NewFileSet(), "x.go", src, parser.AllErrors); err != nil {
		t.Fatalf("output does not parse: %v", err)
	}

	for _, want := range []string{
		"// Code generated by mimic. DO NOT EDIT.\n// source: example.com/suite/domain.Repo\n// source: example.com/suite/domain.Var\n\npackage mocks\n",
		"// If this fails to compile, domain.Repo has changed: run \"mimic gen\".\nvar _ domain.Repo = (*RepoMock)(nil)",
		"type RepoMockGetCall = struct {",
		"callsGet []RepoMockGetCall",
		"sync.Mutex",
		"func (mock *RepoMock) GetCalls() []RepoMockGetCall {",
		`panic("mimic: RepoMock.Get called, but GetFunc is nil")`,
		"DoFunc func(prefix string, xs ...int) (int, error)",
		"Xs     []int",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("output lacks %q", want)
		}
	}

	// A mock has no constructor and does not import testing.
	for _, bad := range []string{"NewRepoMock", `"testing"`} {
		if strings.Contains(src, bad) {
			t.Errorf("output must not contain %q", bad)
		}
	}
}

