func TestGenerate_OwnPackage(t *testing.T) {
	t.Parallel()

	// In the interface's own package an unexported type can be named.
	src, err := generate(t, "example.com/suite/domain", "example.com/suite/domain.U")
	if err != nil {
		t.Fatal(err)
	}

	if !strings.Contains(src, "Use(u unexp) error") || !strings.Contains(src, "var _ U = (*UMock)(nil)") {
		t.Errorf("a mock in the interface's package should name the type:\n%s", src)
	}

	hidden, err := generate(t, "example.com/suite/hidden", "example.com/suite/hidden.Sec")
	if err != nil {
		t.Fatal(err)
	}

	if !strings.Contains(hidden, "func (mock *SecMock) Boxed(b box[int]) box[string]") {
		t.Errorf("unexported generic type should be written by name:\n%s", hidden)
	}
}

func TestGenerate_Refusals(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name  string
		out   string
		specs []string
		want  string
	}{
		{
			name:  "unexported type of another package",
			out:   "example.com/suite/out",
			specs: []string{"example.com/suite/domain.U"},
			want:  "domain.U: domain.unexp is unexported; generate the mock in package domain",
		},
		{
			name:  "unexported type in the interface's own package, output elsewhere",
			out:   "example.com/suite/out",
			specs: []string{"example.com/suite/hidden.Sec"},
			want:  "hidden.Sec: hidden.box is unexported; generate the mock in package hidden",
		},
		{
			name:  "unexported type of an embedded interface",
			out:   "example.com/suite/out",
			specs: []string{"example.com/suite/hcases.Embeds2"},
			want:  "hcases.Embeds2: hidden.box is unexported; generate the mock in package hidden",
		},
		{
			name:  "unknown output package",
			out:   "",
			specs: []string{"example.com/suite/domain.U"},
			want:  "domain.U: domain.unexp is unexported; generate the mock in package domain",
		},
		{
			name:  "struct literal with an unexported field",
			out:   "example.com/suite/out",
			specs: []string{"example.com/suite/hcases.StructLit"},
			want:  "hcases.StructLit: struct literal has unexported field a; generate the mock in package hcases",
		},
		{
			name:  "interface literal with an unexported method",
			out:   "example.com/suite/out",
			specs: []string{"example.com/suite/hcases.IfaceLit"},
			want:  "hcases.IfaceLit: interface literal has unexported method priv; generate the mock in package hcases",
		},
		{
			name:  "defined type of an internal package",
			out:   "example.com/suite/out",
			specs: []string{"example.com/suite/lib.Pipe"},
			want:  "lib.Pipe: example.com/suite/lib/internal/types is internal; generate the mock inside example.com/suite/lib",
		},
		{
			name:  "unexported method of another package",
			out:   "example.com/suite/out",
			specs: []string{"example.com/suite/hcases.PrivMethod"},
			want:  "hcases.PrivMethod: unexported method priv cannot be implemented outside its package",
		},
		{
			name:  "duplicate mock name",
			out:   "example.com/suite/out",
			specs: []string{"example.com/suite/domain.Repo", "example.com/suite/domain.Repo"},
			want:  "would both be generated as RepoMock",
		},
	}

	for _, tt := range tests {
		src, err := generate(t, tt.out, tt.specs...)
		if err == nil || !strings.Contains(err.Error(), tt.want) {
			t.Errorf("%s: got %v, want %q", tt.name, err, tt.want)
		}

		if src != "" {
			t.Errorf("%s: a refusal must not produce source", tt.name)
		}
	}
}

