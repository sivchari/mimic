func TestGenerate_SkipEnsure(t *testing.T) {
	t.Parallel()

	const out = "example.com/suite/out"

	tests := []struct {
		name       string
		specs      []string
		skip       bool
		wantEnsure bool
		wantImport bool // whether the source package domain is imported
	}{
		{name: "ensure by default", specs: []string{"example.com/suite/domain.Repo"}, wantEnsure: true, wantImport: true},
		{name: "skipped", specs: []string{"example.com/suite/domain.Repo"}, skip: true},
		{name: "skipped, generic", specs: []string{"example.com/suite/domain.GRepo"}, skip: true},
		{name: "skipped, several", specs: []string{"example.com/suite/domain.Repo", "example.com/suite/domain.Var"}, skip: true},
		// MyInt is declared in domain and written as domain.MyInt, so the import is needed anyway.
		{name: "skipped, source package named by a type", specs: []string{"example.com/suite/domain.Al"}, skip: true, wantImport: true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			src, err := generateWith(t, emit.Options{OutPath: out, SkipEnsure: tt.skip}, tt.specs...)
			if err != nil {
				t.Fatal(err)
			}

			if got := strings.Contains(src, "If this fails to compile"); got != tt.wantEnsure {
				t.Errorf("ensure comment present = %v, want %v", got, tt.wantEnsure)
			}

			if got := strings.Contains(src, "= (*"); got != tt.wantEnsure {
				t.Errorf("ensure line present = %v, want %v", got, tt.wantEnsure)
			}

			if got := strings.Contains(src, `"example.com/suite/domain"`); got != tt.wantImport {
				t.Errorf("source import present = %v, want %v:\n%s", got, tt.wantImport, src)
			}

			if _, err := parser.ParseFile(token.NewFileSet(), "x.go", src, parser.AllErrors); err != nil {
				t.Fatalf("output does not parse: %v", err)
			}
		})
	}
}

// params reads the generated source and returns, for each method of the mock mockName, the
// parameters as "variable:Field" pairs: the variable is the name in the method signature and the
// field is the name in the call record.
func params(t *testing.T, src, mockName string) map[string][]string {
	t.Helper()

	f, err := parser.ParseFile(token.NewFileSet(), "x.go", src, parser.AllErrors)
	if err != nil {
		t.Fatalf("output does not parse: %v\n%s", err, src)
	}

	vars := map[string][]string{}
	fields := map[string][]string{}

	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}

		for _, sp := range gd.Specs {
			ts, ok := sp.(*ast.TypeSpec)
			if !ok {
				continue
			}

			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				continue
			}

			switch {
			case ts.Name.Name == mockName:
				for _, fl := range st.Fields.List {
					ft, ok := fl.Type.(*ast.FuncType)
					if !ok {
						continue
					}

					m := strings.TrimSuffix(fl.Names[0].Name, "Func")
					for _, p := range ft.Params.List {
						for _, n := range p.Names {
							vars[m] = append(vars[m], n.Name)
						}
					}
				}
			case strings.HasPrefix(ts.Name.Name, mockName) && strings.HasSuffix(ts.Name.Name, "Call"):
				m := strings.TrimSuffix(strings.TrimPrefix(ts.Name.Name, mockName), "Call")
				for _, fl := range st.Fields.List {
					fields[m] = append(fields[m], fl.Names[0].Name)
				}
			}
		}
	}

	out := map[string][]string{}

	for m, fs := range fields {
		if len(vars[m]) != len(fs) {
			t.Fatalf("%s: %d variables but %d fields", m, len(vars[m]), len(fs))
		}

		out[m] = []string{}
		for i := range fs {
			out[m] = append(out[m], vars[m][i]+":"+fs[i])
		}
	}

	return out
}

// TestGenerate_ParamNames follows moq v0.6.0 for the field names and, except where the body needs
// another name, for the variable names too.
func TestGenerate_ParamNames(t *testing.T) {
	t.Parallel()

	tests := []struct {
		spec string
		want map[string][]string
	}{
		{"example.com/suite/domain.Names", map[string][]string{
			"A":       {"n:N", "s:S"},
			"B":       {"n:N", "mock_:Mock", "fn:Fn"},
			"ABefore": {"context:Context", "domain:Domain", "sync:Sync"},
			// An unnamed context.Context takes the name of its package, which is an import.
			"Ctx": {"contextMoqParam:ContextMoqParam", "err:Err"},
			// An explicit name that is an import name gets the suffix; ctx is not an import.
			"Imports": {"modelMoqParam:ModelMoqParam", "otherMoqParam:OtherMoqParam", "ctx:Ctx"},
			// Only a name that is a whole initialism is upper-cased.
			"Initialisms": {"html:HTML", "id:ID", "url:URL", "userID:UserID", "ctx:Ctx"},
			// The renaming of the first duplicate collides with the explicit n1, as in moq.
			"Dups":  {"n11:N11", "n2:N2", "n3:N3", "s1:S1", "s2:S2", "n12:N12"},
			"Kinds": {"strings:Strings", "ints:Ints", "stringToInt:StringToInt", "intCh:IntCh", "fn:Fn", "n:N", "user:User", "users:Users", "val:Val", "ifaceVal:IfaceVal", "errCh:ErrCh"},
			// Unsigned integers, complex numbers, byte, aliases and any are all "v".
			"Basics": {"b:B", "n1:N1", "v1:V1", "f:F", "v2:V2", "v3:V3", "n2:N2", "v4:V4", "v5:V5", "bytes:Bytes", "runes:Runes"},
			"Pkgs":   {"timeMoqParam1:TimeMoqParam1", "duration:Duration", "timeMoqParam2:TimeMoqParam2", "durations:Durations", "reader:Reader"},
			"Vari":   {"strings:Strings"},
			// other.Alias is an alias of other.Thing, which moq's go/types sees as an alias type.
			"Aliases": {"v:V", "vs:Vs", "fn:Fn", "things:Things"},
			// The result variable nOut takes the name of the parameter first, which becomes nOut1.
			"Out": {"nOut1:NOut1"},
			// The variable avoids what the body uses; the field keeps the name.
			"Body": {"mock_:Mock", "callInfo_:CallInfo", "panic_:Panic", "append_:Append", "NamesMockBodyCall_:NamesMockBodyCall"},
		}},
		{"example.com/suite/domain.GNames", map[string][]string{
			"Put": {"v1:V1", "vs:Vs", "v2:V2", "stringToV:StringToV"},
		}},
		{"example.com/suite/domain.GNamesString", map[string][]string{
			"Put": {"s1:S1", "strings:Strings", "s2:S2", "stringToString:StringToString"},
		}},
	}

	for _, tt := range tests {
		t.Run(tt.spec, func(t *testing.T) {
			t.Parallel()

			src, err := generate(t, "example.com/suite/out", tt.spec)
			if err != nil {
				t.Fatal(err)
			}

			got := params(t, src, tt.spec[strings.LastIndex(tt.spec, ".")+1:]+"Mock")

			for m, want := range tt.want {
				if !slices.Equal(got[m], want) {
					t.Errorf("%s:\n got %v\nwant %v", m, got[m], want)
				}
			}

			if len(got) != len(tt.want) {
				t.Errorf("got %d methods, want %d", len(got), len(tt.want))
			}
		})
	}
}
